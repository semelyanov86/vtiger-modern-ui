	seed) cmd_seed ;;
	import-zip) shift; cmd_import_zip "$@" ;;
	uninstall) cmd_uninstall ;;
	verify) shift; ensure_secrets; cmd_verify "$@" ;;
	status) cmd_status ;;
	hash) shift; ensure_secrets; cmd_hash "$@" ;;
	meta) shift; cmd_meta "$@" ;;
	query) shift; cmd_query "$@" ;;
	php) shift; ensure_secrets; cmd_php "$@" ;;
	logs) shift; ensure_secrets; cmd_logs "$@" ;;
	log-mark) ensure_secrets; cmd_log_mark ;;
	strict-log) ensure_secrets; cmd_strict_log ;;
	down) cmd_down ;;
	reset) cmd_reset ;;
	*) sed -n '2,27p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 2 ;;
esac
