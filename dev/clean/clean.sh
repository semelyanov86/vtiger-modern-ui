#!/usr/bin/env bash
# Clean Vtiger 8.4.0 stand of ModernUI (docs/environments.md §2): Docker project dev/clean/, the official release
# archive of 8.4.0 (pinned SHA-256), new empty databases, the standard web installer, synthetic data. No dump or patch of the dev instance, no
# link of src/, no watcher, no Vite: ModernUI gets there only as the ZIP imported by the Module Manager.
#
#   dev/clean/clean.sh up                 build images, start, unpack 8.4.0 into empty CRM volumes   (task clean:up)
#   dev/clean/clean.sh verify-source      compare the release archive with the tag 8.4.0 (VTIGER_SRC_REPO)
#   dev/clean/clean.sh install            run the web installer of each CRM that is not installed     (task clean:install)
#   dev/clean/clean.sh seed               synthetic roles, users, records, the Gadgets test module    (task clean:seed)
#   dev/clean/clean.sh import-zip [ZIP]   ModernUI ZIP through Settings → Module Manager → Import      (task clean:import-zip)
#   dev/clean/clean.sh uninstall          vtlib console --remove=ModernUI, then the module files       (task clean:uninstall)
#   dev/clean/clean.sh verify [ZIP]       NEW stand and the whole PACKAGE check of a ZIP (deletes data) (task clean:verify)
#   dev/clean/clean.sh status             containers, URLs, versions, ModernUI registration           (task clean:status)
#   dev/clean/clean.sh hash <label>       SHA-256 of the CRM code files (without runtime dirs)        (task clean:hash)
#   dev/clean/clean.sh meta <label>       metadata of the CRM DB: tabs, links, settings items, tables (task clean:meta)
#   dev/clean/clean.sh query <inst> SQL   read-only SELECT/SHOW against a CRM database
#   dev/clean/clean.sh php <inst> ARGS    php inside the web container of an instance, as www-data
#   dev/clean/clean.sh logs [inst]        PHP messages of logs/phperr.log, grouped; ModernUI ones listed (task clean:logs)
#   dev/clean/clean.sh log-mark           current line count of each phperr.log (for MU_LOG_SINCE)
#   dev/clean/clean.sh strict-log         E_ALL into logs/phperr.log via the shipped config_override.dev.php
#   dev/clean/clean.sh down               stop; volumes stay                                          (task clean:down)
#   dev/clean/clean.sh reset              stop and DELETE the volumes of this project (new empty DBs) (task clean:reset)
#
# Instances (MU_CLEAN_INSTANCES, default "c81 c85"): c81 — PHP 8.1, site root; c85 — PHP 8.5, /vtigercrm/.
# Secrets are generated once into .local/clean/secrets.env (not in git); per-instance settings for the browser
# tests go to .local/clean/<instance>.env.
set -euo pipefail

REPO=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)
HERE=$REPO/dev/clean
PRESET_SRC_REPO=${VTIGER_SRC_REPO:-}
if [[ -f "$REPO/.env" ]]; then
	set -a
	# shellcheck disable=SC1091
	source "$REPO/.env"
	set +a
fi
VTIGER_SRC_REPO=${VTIGER_SRC_REPO:-$PRESET_SRC_REPO}
LOCAL=$REPO/.local/clean
SECRETS=$LOCAL/secrets.env
export MU_CLEAN_PORT=${MU_CLEAN_PORT:-8481}
export MU_CLEAN85_PORT=${MU_CLEAN85_PORT:-8485}
export MU_CLEAN_MAIL_PORT=${MU_CLEAN_MAIL_PORT:-8425}
INSTANCES=${MU_CLEAN_INSTANCES:-c81 c85}
# Official source: the release archive of Vtiger 8.4.0 on SourceForge (the download link of vtiger.com). The git tag
# 8.4.0 (commit below) has the same code but no vendor/ ("Please install composer dependencies"); verify-source
# compares the two. MU_CLEAN_TARBALL may point to a local copy of the same archive.
VERSION=8.4.0
RELEASE_URL='https://sourceforge.net/projects/vtigercrm/files/vtiger%20CRM%208.4.0/Core%20Product/vtigercrm8.4.0.tar.gz/download'
RELEASE_SHA256=9f903946e5fe9befa8b91ff96c51518117ca0850b788dee0713b8661d4c500b3
TAG_COMMIT=0bb3774e7df04c40bc2cc81b1f910a6b1ae77be2
TARBALL=${MU_CLEAN_TARBALL:-$LOCAL/vtigercrm$VERSION.tar.gz}

die() {
	echo "clean: $*" >&2
	exit 1
}

compose() {
	docker compose --project-directory "$HERE" -f "$HERE/compose.yaml" "$@"
}

# Instance → service, document root of the CRM, base path, port, database.
service() { case $1 in c81) echo web81 ;; c85) echo web85 ;; *) die "unknown instance $1 (c81, c85)" ;; esac; }
crm_dir() { case $1 in c81) echo /var/www/html ;; c85) echo /var/www/html/vtigercrm ;; esac; }
base_path() { case $1 in c81) echo / ;; c85) echo /vtigercrm/ ;; esac; }
port() { case $1 in c81) echo "$MU_CLEAN_PORT" ;; c85) echo "$MU_CLEAN85_PORT" ;; esac; }
db_name() { echo "vtiger_$1"; }
url() { echo "http://127.0.0.1:$(port "$1")$(base_path "$1")"; }

secret() {
	# 20 random characters plus classes the Vtiger password rule asks for.
	printf 'Mu%s#7a' "$(head -c 48 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c 18)"
}

ensure_secrets() {
	mkdir -p "$LOCAL"
	chmod 700 "$LOCAL"
	if [[ ! -f $SECRETS ]]; then
		umask 077
		{
			echo "# Generated by dev/clean/clean.sh — passwords of the clean stand only. Not in git."
			echo "MU_CLEAN_DB_ROOT_PASSWORD=$(secret)"
			echo "MU_CLEAN_DB_PASSWORD=$(secret)"
			echo "MU_CLEAN_ADMIN_PASSWORD=$(secret)"
			echo "MU_CLEAN_USERS_PASSWORD=$(secret)"
		} >"$SECRETS"
	fi
	set -a
	# shellcheck disable=SC1090
	source "$SECRETS"
	set +a
}

write_instance_env() {
	local inst=$1
	umask 077
	cat >"$LOCAL/$inst.env" <<-EOF
		# Generated by dev/clean/clean.sh — settings of the browser tests for the clean instance $inst (not in git).
		CRM_URL=$(url "$inst")
		CRM_ADMIN_USER=admin
		CRM_ADMIN_PASS=$MU_CLEAN_ADMIN_PASSWORD
		MU_USERS_PASS=$MU_CLEAN_USERS_PASSWORD
		MU_DB_NAME=$(db_name "$inst")
		MU_INSTANCE=$inst
	EOF
}

source_tarball() {
	if [[ ! -f $TARBALL ]]; then
		echo "clean: downloading the release archive of Vtiger $VERSION"
		curl -fsSL --retry 3 -o "$TARBALL.tmp" "$RELEASE_URL"
		mv "$TARBALL.tmp" "$TARBALL"
	fi
	local sum
	sum=$(sha256sum "$TARBALL" | cut -d' ' -f1)
	[[ $sum == "$RELEASE_SHA256" ]] || die "$TARBALL: SHA-256 $sum, expected $RELEASE_SHA256"
	echo "release vtigercrm$VERSION.tar.gz sha256 $sum" >"$LOCAL/source.txt"
}

# The release archive against the tag: same files except vendor/, composer.lock and install-composer-deps.sh.
cmd_verify_source() {
	source_tarball
	local repo=${VTIGER_SRC_REPO:-}
	[[ -n $repo ]] || die "set VTIGER_SRC_REPO in .env: a git clone of https://code.vtiger.com/vtiger/vtigercrm"
	local commit
	commit=$(git -C "$repo" rev-parse "$VERSION^{commit}" 2>/dev/null) || die "no tag $VERSION in $repo"
	[[ $commit == "$TAG_COMMIT" ]] || die "tag $VERSION of $repo is $commit, expected $TAG_COMMIT"
	local work
	work=$(mktemp -d "$LOCAL/verify.XXXXXX")
	mkdir "$work/release" "$work/tag"
	tar -xzf "$TARBALL" -C "$work/release" --strip-components=1
	git -C "$repo" archive --format=tar "$VERSION" | tar -x -C "$work/tag"
	local differences
	differences=$(LC_ALL=C diff -rq "$work/release" "$work/tag" | sed "s#$work/##g" | grep -v '^Only in release/vendor' | grep -v '^Only in release: vendor$' || true)
	rm -rf "$work"
	echo "tag $VERSION commit $commit; differences besides vendor/:"
	printf "  %s\n" "${differences:-(none)}"
	echo "tag $VERSION commit $commit — release differs only by: $(echo "$differences" | tr '\n' ';')" >>"$LOCAL/source.txt"
}

cmd_up() {
	ensure_secrets
	source_tarball
	compose build --pull=false
	compose up -d --wait
	local inst svc dir
	for inst in $INSTANCES; do
		svc=$(service "$inst")
		dir=$(crm_dir "$inst")
		if compose exec -T "$svc" test -f "$dir/vtigerversion.php"; then
			echo "clean: $inst has the CRM code already"
		else
			echo "clean: unpacking Vtiger $VERSION into $inst ($dir)"
			compose exec -T "$svc" tar -xz --strip-components=1 -C "$dir" -f - <"$TARBALL"
			compose exec -T "$svc" chown -R www-data:www-data "$dir"
		fi
		write_instance_env "$inst"
	done
	cat "$LOCAL/source.txt"
	cmd_status
}

installed() {
	compose exec -T "$(service "$1")" php -r '$dbconfig = []; @include $argv[1]; exit(empty($dbconfig["db_name"]) || $dbconfig["db_name"] === "_DBC_TYPE_" ? 1 : 0);' \
		"$(crm_dir "$1")/config.inc.php"
}

cmd_install() {
	ensure_secrets
	local inst
	for inst in $INSTANCES; do
		write_instance_env "$inst"
		if installed "$inst"; then
			echo "clean: $inst is installed already"
			continue
		fi
		echo "clean: running the Vtiger installer of $inst ($(url "$inst"))"
		(cd "$REPO/frontend" && MU_E2E_TARGET=$inst MU_CLEAN_DB_PASSWORD=$MU_CLEAN_DB_PASSWORD \
			npx playwright test --config e2e/playwright.config.ts --project install)
		installed "$inst" || die "$inst: the installer did not write config.inc.php"
	done
	cmd_strict_log
}

# PHP messages of every level into logs/phperr.log of the CRM: the switch Vtiger 8.4.0 ships for developers
# (config_override.dev.php copied to config_override.php, read by config.php). Without it config.php keeps only
# E_ERROR for web requests. No file of the CRM code is changed.
cmd_strict_log() {
	local inst svc dir
	for inst in $INSTANCES; do
		svc=$(service "$inst")
		dir=$(crm_dir "$inst")
		if compose exec -T "$svc" test -f "$dir/config_override.php"; then
			continue
		fi
		compose exec -T -u www-data "$svc" cp "$dir/config_override.dev.php" "$dir/config_override.php"
		echo "clean: $inst — strict PHP log on (config_override.php from config_override.dev.php → logs/phperr.log)"
	done
}

# Settings → Module Manager → Import of a ZIP under the administrator (browser, frontend/e2e/tools/module-import.spec.ts).
import_zip() {
	local inst=$1 zip=$2 expect=${3:-any}
	[[ -f $zip ]] || die "no such ZIP: $zip"
	(cd "$REPO/frontend" && MU_E2E_TARGET=$inst MU_IMPORT_ZIP=$(realpath "$zip") MU_IMPORT_EXPECT=$expect \
		npx playwright test --config e2e/playwright.config.ts --project import)
}

# The test entity module (tests/fixtures/gadgets) as a vtlib package.
fixture_zip() {
	local out=$LOCAL/Gadgets-1.0.0.zip
	(cd "$REPO/tests/fixtures/gadgets" && rm -f "$out" && python3 -c 'import sys, zipfile, os
with zipfile.ZipFile(sys.argv[1], "w", zipfile.ZIP_DEFLATED) as z:
	for base, _, files in os.walk("."):
		for name in sorted(files):
			path = os.path.join(base, name)[2:]
			z.write(path, path)' "$out")
	echo "$out"
}

cmd_seed() {
	ensure_secrets
	local inst zip
	zip=$(fixture_zip)
	for inst in $INSTANCES; do
		installed "$inst" || die "$inst is not installed (task clean:install)"
		compose exec -T -u www-data -e MU_USERS_PASSWORD="$MU_CLEAN_USERS_PASSWORD" "$(service "$inst")" \
			php /opt/mu-dev/clean/tools/seed.php "$(crm_dir "$inst")"
		if [[ -z $(mysql_ro "$inst" "SELECT tabid FROM vtiger_tab WHERE name = 'Gadgets'") ]]; then
			echo "clean: $inst — importing the test entity module Gadgets through the Module Manager"
			import_zip "$inst" "$zip" import
			compose exec -T -u www-data -e MU_USERS_PASSWORD="$MU_CLEAN_USERS_PASSWORD" "$(service "$inst")" \
				php /opt/mu-dev/clean/tools/seed.php "$(crm_dir "$inst")"
		fi
	done
}

# Uninstall of ModernUI as an administrator of a plain 8.4.0 does it (docs/environments.md §2.3):
# 1. vtlib console "--remove=ModernUI" (Vtiger_Module::delete(): links, settings item, profiles; the settings tables
#    stay by the policy of settings.md). The console of the 8.4.0 release does not load the composer autoloader and
#    dies silently ("Monolog\Logger" not found), so it runs with php -d auto_prepend_file=vendor/autoload.php;
# 2. the module files (the paths of dev/crm-mounts.txt): the core never deletes them, and while modules/ModernUI
#    exists the Module Manager offers only "Update", which fails for a module that is not registered.
cmd_uninstall() {
	ensure_secrets
	local inst svc dir
	for inst in $INSTANCES; do
		svc=$(service "$inst")
		dir=$(crm_dir "$inst")
		compose exec -T -u www-data -w "$dir" "$svc" php -d auto_prepend_file=vendor/autoload.php vtlib/tools/console.php --remove=ModernUI 2>&1 \
			| grep -v 'Deprecated' || true
		compose exec -T -u www-data -w "$dir" "$svc" sh -c 'grep -vE "^(#|$)" /opt/mu-dev/crm-mounts.txt | while read -r pattern; do
			for path in $pattern; do [ -e "$path" ] && rm -rf "$path" && echo "  removed $path"; done; done; true'
		echo "clean: $inst — ModernUI removed (settings tables kept)"
	done
}

# ModernUI ZIP (default: the one of VERSION in dist/) into every instance through the Module Manager.
cmd_import_zip() {
	ensure_secrets
	local zip=${1:-$REPO/dist/ModernUI-$(cat "$REPO/VERSION").zip} inst
	for inst in $INSTANCES; do
		installed "$inst" || die "$inst is not installed (task clean:install)"
		echo "clean: $inst — Module Manager import of $(basename "$zip") (sha256 $(sha256sum "$zip" | cut -c1-16)…)"
		import_zip "$inst" "$zip" any
	done
}

cmd_status() {
	ensure_secrets
	compose ps --format 'table {{.Service}}\t{{.State}}\t{{.Status}}'
	echo "mail: http://127.0.0.1:$MU_CLEAN_MAIL_PORT/"
	[[ -f $LOCAL/source.txt ]] && sed 's/^/source: /' "$LOCAL/source.txt"
	local inst svc code
	for inst in $INSTANCES; do
		svc=$(service "$inst")
		code=$(curl -s -o /dev/null -w '%{http_code}' "$(url "$inst")index.php" || true)
		echo "$inst: $(url "$inst") — HTTP $code"
		if ! compose exec -T "$svc" true 2>/dev/null; then
			echo "  not running"
			continue
		fi
		compose exec -T "$svc" php -r 'echo "  PHP ", PHP_VERSION, ", imap ", extension_loaded("imap") ? "yes" : "no", "\n";'
		compose exec -T "$svc" sh -c "sed -n \"s/^\\\$vtiger_current_version *= *'\\([^']*\\)'.*/  Vtiger \\1/p\" $(crm_dir "$inst")/vtigerversion.php 2>/dev/null || echo '  no CRM code'"
		if installed "$inst"; then
			compose exec -T "$svc" php /opt/mu-dev/crm-info.php "$(crm_dir "$inst")" ModernUI
			compose exec -T "$svc" sh -c "cd $(crm_dir "$inst") && for p in modules/ModernUI modules/Settings/ModernUI layouts/v7/modules/ModernUI layouts/v7/modules/Settings/ModernUI; do [ -e \"\$p\" ] && echo \"  files: \$p (\$(find \"\$p\" -type f | wc -l) files)\"; done; true"
		else
			echo "  not installed (task clean:install)"
		fi
	done
}

# Files of the CRM code: everything except what the CRM itself writes at runtime.
cmd_hash() {
	local label=${1:?label}
	mkdir -p "$LOCAL/hashes"
	local inst
	for inst in $INSTANCES; do
		compose exec -T "$(service "$inst")" sh -c "cd $(crm_dir "$inst") && find . -type f \
			! -path './cache/*' ! -path './storage/*' ! -path './logs/*' ! -path './test/*' ! -path './user_privileges/*' \
			! -path './backup/*' ! -name 'tabdata.php' ! -name 'parent_tabdata.php' ! -name 'config.inc.php' ! -name 'config_override.php' \
			-print0 | sort -z | xargs -0 sha256sum" >"$LOCAL/hashes/$inst-$label.txt"
		echo "clean: $inst — $(wc -l <"$LOCAL/hashes/$inst-$label.txt") code files hashed → .local/clean/hashes/$inst-$label.txt"
	done
}

mysql_ro() {
	local inst=$1
	shift
	compose exec -T -e MYSQL_PWD="$MU_CLEAN_DB_ROOT_PASSWORD" db mysql -uroot --default-character-set=utf8mb4 --batch --skip-column-names "$(db_name "$inst")" -e "$*"
}

cmd_query() {
	ensure_secrets
	local inst=${1:?instance}
	shift
	local sql="$*"
	[[ $sql =~ ^[[:space:]]*(SELECT|SHOW|select|show)[[:space:]] ]] || die "query: only SELECT/SHOW"
	[[ $sql != *';'* ]] || die "query: one statement, no ';'"
	mysql_ro "$inst" "$sql"
}

cmd_meta() {
	ensure_secrets
	local label=${1:?label}
	mkdir -p "$LOCAL/meta"
	local inst out
	for inst in $INSTANCES; do
		out=$LOCAL/meta/$inst-$label.txt
		{
			echo "## tables"
			mysql_ro "$inst" "SELECT table_name, table_collation FROM information_schema.tables WHERE table_schema = DATABASE() ORDER BY table_name"
			echo "## schema"
			mysql_ro "$inst" "SELECT default_character_set_name, default_collation_name FROM information_schema.schemata WHERE schema_name = DATABASE()"
			echo "## vtiger_tab"
			mysql_ro "$inst" "SELECT tabid, name, presence, isentitytype, version FROM vtiger_tab ORDER BY tabid"
			echo "## global links"
			mysql_ro "$inst" "SELECT tabid, linktype, linklabel, linkurl, handler_path, handler_class, handler FROM vtiger_links WHERE linktype IN ('HEADERSCRIPT','HEADERCSS','HEADERLINK') ORDER BY linktype, linklabel"
			echo "## settings items"
			mysql_ro "$inst" "SELECT blockid, name, linkto, active FROM vtiger_settings_field ORDER BY blockid, sequence, name"
			echo "## profile2tab"
			mysql_ro "$inst" "SELECT COUNT(*), SUM(permissions) FROM vtiger_profile2tab"
			echo "## roles and profiles"
			mysql_ro "$inst" "SELECT roleid, rolename, parentrole FROM vtiger_role ORDER BY roleid"
			mysql_ro "$inst" "SELECT profileid, profilename FROM vtiger_profile ORDER BY profileid"
			echo "## users"
			mysql_ro "$inst" "SELECT id, user_name, is_admin, status FROM vtiger_users ORDER BY id"
			echo "## records per module"
			mysql_ro "$inst" "SELECT setype, COUNT(*) FROM vtiger_crmentity WHERE deleted = 0 GROUP BY setype ORDER BY setype"
		} >"$out"
		echo "clean: $inst — DB metadata → .local/clean/meta/$inst-$label.txt"
	done
}

# Browser scenarios against one instance (frontend/e2e, project and extra arguments of playwright).
e2e() {
	local inst=$1
	shift
	(cd "$REPO/frontend" && MU_E2E_TARGET=$inst npx playwright test --config e2e/playwright.config.ts "$@")
}

privileges_mtime() {
	local inst=$1 id
	id=$(mysql_ro "$inst" "SELECT id FROM vtiger_users WHERE user_name = 'mu.limited'")
	compose exec -T "$(service "$inst")" stat -c '%Y' "$(crm_dir "$inst")/user_privileges/user_privileges_$id.php"
}

# Every difference between two hash lists must be a file of ModernUI.
check_hashes() {
	local inst=$1 before=$2 after=$3 other
	other=$(diff "$LOCAL/hashes/$inst-$before.txt" "$LOCAL/hashes/$inst-$after.txt" | grep -E '^[<>]' | grep -v 'ModernUI' || true)
	[[ -z $other ]] || die "$inst: CRM files changed between $before and $after:\n$other"
	echo "clean: $inst — CRM code files unchanged ($before → $after); ModernUI files added: $(diff "$LOCAL/hashes/$inst-$before.txt" "$LOCAL/hashes/$inst-$after.txt" | grep -c '^>' || true)"
}

# The whole PACKAGE check of a ZIP on new clean instances (docs/environments.md §2.4, docs/verification.md):
# reset → up → install → seed → hashes → baseline → Module Manager import → privileges of U untouched while U gets the theme
# (Q2) → scenarios → Module Manager update of the same ZIP → uninstall → import again (reinstall, L8) → hashes and
# the PHP log. DELETES the data of the clean stand first. Report: .local/clean/verify-<time>.txt.
cmd_verify() {
	local zip=${1:-$REPO/dist/ModernUI-$(cat "$REPO/VERSION").zip}
	[[ -f $zip ]] || die "no such ZIP: $zip (task package)"
	zip=$(realpath "$zip")
	local report
	report=$LOCAL/verify-$(date +%F-%H%M%S).txt
	mkdir -p "$LOCAL"
	(
		set -euo pipefail
		echo "verify: $(basename "$zip") sha256 $(sha256sum "$zip" | cut -d' ' -f1), instances: $INSTANCES"
		cmd_reset
		cmd_up
		cmd_install
		cmd_seed
		cmd_hash before
		cmd_meta before
		local inst marks
		marks=$(cmd_log_mark)
		echo "$marks" >"$LOCAL/log-marks-verify.txt"
		for inst in $INSTANCES; do
			# Baseline without the theme; it also signs every synthetic user in once — the first sign-in saves the
			# user (UserSetup) and so rebuilds the privilege files, which must not count against the import.
			e2e "$inst" --project baseline
			local privileges
			privileges=$(privileges_mtime "$inst")
			echo "clean: $inst — Module Manager import"
			import_zip "$inst" "$zip" import
			cmd_hash after-import
			check_hashes "$inst" before after-import
			(export MU_FRESH_IMPORT=1 && e2e "$inst" --project clean -g 'after the import|settings:|enable for me|pilot by user')
			[[ $(privileges_mtime "$inst") == "$privileges" ]] || die "$inst: privilege files of U were rebuilt"
			echo "clean: $inst — U got the theme with the privilege files untouched (Q2)"
			# The rest of clean.spec.ts continues from the state the first part left (U in the pilot).
			e2e "$inst" --project clean -g 'pilot by role|languages|cannot open|Module Manager:|standard view|network'
			e2e "$inst" --project modernui
			echo "clean: $inst — Module Manager update with the same ZIP"
			import_zip "$inst" "$zip" update
			e2e "$inst" --project modernui
		done
		cmd_meta after-scenarios
		cmd_uninstall
		cmd_meta after-uninstall
		for inst in $INSTANCES; do
			if grep -qE 'ModernUI' <(sed -n '/## vtiger_tab/,/## settings items/p;/## settings items/,/## profile2tab/p' "$LOCAL/meta/$inst-after-uninstall.txt"); then
				die "$inst: ModernUI registrations left after uninstall"
			fi
			grep -q 'vtiger_modernui_settings' "$LOCAL/meta/$inst-after-uninstall.txt" || die "$inst: settings tables were dropped"
			echo "clean: $inst — uninstall: no tab, links or settings item; settings tables kept"
			(export MU_BASELINE_LABEL=after-uninstall && e2e "$inst" --project baseline)
			echo "clean: $inst — reinstall through the Module Manager"
			import_zip "$inst" "$zip" import
			(export MU_EXPECT_REINSTALL=1 && e2e "$inst" --project clean)
		done
		cmd_hash after-all
		for inst in $INSTANCES; do
			check_hashes "$inst" before after-all
			MU_CLEAN_INSTANCES=$inst MU_LOG_SINCE=$(awk -v i="$inst" '$1 == i {print $2}' "$LOCAL/log-marks-verify.txt") cmd_logs "$inst"
		done
		echo "verify: PASSED"
	) 2>&1 | tee "$report"
	[[ ${PIPESTATUS[0]} -eq 0 ]] || die "verify FAILED, report: $report"
	echo "clean: report $report"
}

cmd_php() {
	local inst=${1:?instance}
	shift
	compose exec -T -u www-data -w "$(crm_dir "$inst")" "$(service "$inst")" php "$@"
}

# PHP messages: logs/phperr.log of each CRM (strict log), grouped; messages from ModernUI files listed in full.
# MU_LOG_SINCE=<line> skips the first lines (task clean:logs counts from a mark of clean.sh log-mark).
cmd_logs() {
	local insts=${1:-$INSTANCES} inst svc dir
	for inst in $insts; do
		svc=$(service "$inst")
		dir=$(crm_dir "$inst")
		echo "== $inst — $dir/logs/phperr.log (from line $((${MU_LOG_SINCE:-0} + 1)))"
		compose exec -T "$svc" sh -c "[ -f $dir/logs/phperr.log ] && tail -n +$((${MU_LOG_SINCE:-0} + 1)) $dir/logs/phperr.log || true" >"$LOCAL/phperr-$inst.txt"
		# Format of Vtiger_PhpLogHandler: "[date]@[time] <Type>: <message> in <file> on line <n>", each after a
		# "[date]@[time] <METHOD> <request>" context line.
		echo "  messages: $(grep -cvE '\] (GET|POST|PUT|DELETE|HEAD) ' "$LOCAL/phperr-$inst.txt" || true); by type and file:"
		grep -vE '\] (GET|POST|PUT|DELETE|HEAD) ' "$LOCAL/phperr-$inst.txt" | sed -E 's/^\[[^]]*\]@\[[^]]*\] //' \
			| sed -E 's/^([A-Za-z ()0-9]+): .* in ([^ ]+) on line [0-9]+.*/\1 \2/; s#test/templates_c/v7/[0-9a-f]+_[0-9]+\.file\.#templates_c/…#' \
			| sort | uniq -c | sort -rn | head -"${MU_LOG_TOP:-15}" | sed 's/^/    /'
		# Messages raised in files of ModernUI (the request context lines are not messages).
		echo "  in ModernUI files:"
		grep -vE '\] (GET|POST|PUT|DELETE|HEAD) ' "$LOCAL/phperr-$inst.txt" | grep -E ' in [^ ]*ModernUI[^ ]* on line' | head -20 | sed 's/^/    /' || true
		grep -vE '\] (GET|POST|PUT|DELETE|HEAD) ' "$LOCAL/phperr-$inst.txt" | grep -qE ' in [^ ]*ModernUI[^ ]* on line' || echo "    (none)"
		# PHP's own lines ("[01-Nov-2026 …] PHP …", CLI runs such as the vtlib console) end a request context.
		echo "  during requests to ModernUI pages: $(awk '/\] (GET|POST|PUT|DELETE|HEAD) /{ctx=$0; next} /^\[[0-9][0-9]-[A-Z][a-z][a-z]-/{ctx=""} ctx ~ /module=ModernUI/' "$LOCAL/phperr-$inst.txt" | sed -E 's/^\[[^]]*\]@\[[^]]*\] //; s/ on line [0-9]+//' | sort | uniq -c | tr -s ' ' | paste -sd ';' || true)"
	done
}

cmd_log_mark() {
	local inst
	for inst in $INSTANCES; do
		echo "$inst $(compose exec -T "$(service "$inst")" sh -c "[ -f $(crm_dir "$inst")/logs/phperr.log ] && wc -l < $(crm_dir "$inst")/logs/phperr.log || echo 0")"
	done
}

cmd_down() {
	ensure_secrets
	compose down
}

cmd_reset() {
	ensure_secrets
	compose down -v --remove-orphans
	rm -f "$LOCAL"/c*.env "$LOCAL"/e2e-*-state.json
	echo "clean: volumes of the clean stand removed; next: task clean:up, task clean:install"
}

case ${1:-} in
